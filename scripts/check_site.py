"""Check built HTML for missing local resources, links and fragment targets."""

import argparse
import re
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urljoin, urlsplit


class Page(HTMLParser):
    def __init__(self, path):
        super().__init__(convert_charrefs=True)
        self.ids = set()
        self.links = []
        self.duplicate_ids = []
        self.feed(path.read_text(encoding="utf-8"))

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get("id"):
            if attrs["id"] in self.ids:
                self.duplicate_ids.append(attrs["id"])
            self.ids.add(attrs["id"])
        for attr in ("href", "src", "poster"):
            if attrs.get(attr):
                self.links.append(attrs[attr])


def check_site(destination, baseurl):
    root = Path(destination).resolve()
    pages = {path: Page(path) for path in root.rglob("*.html")}
    errors = []
    if root / "index.html" not in pages:
        errors.append("index.html is missing")
    for path, page in pages.items():
        relative = path.relative_to(root).as_posix()
        errors.extend(f"{relative}: duplicate id {value}" for value in page.duplicate_ids)
        page_url = f"https://site.invalid{baseurl}/{relative}"
        for link in page.links:
            parsed = urlsplit(link)
            if parsed.scheme or parsed.netloc:
                continue
            resolved = urlsplit(urljoin(page_url, link))
            url_path = unquote(resolved.path)
            prefix = baseurl + "/"
            if not url_path.startswith(prefix):
                errors.append(f"{relative}: link leaves baseurl: {link}")
                continue
            target = (root / url_path[len(prefix):]).resolve()
            if not target.is_relative_to(root):
                errors.append(f"{relative}: link leaves destination: {link}")
                continue
            if target.is_dir():
                target /= "index.html"
            if not target.is_file():
                errors.append(f"{relative}: missing target: {link}")
                continue
            fragment = unquote(resolved.fragment)
            if fragment and target in pages and fragment not in pages[target].ids:
                # These IDs are generated by the chapter reader in the browser.
                if not re.fullmatch(r"(?:chapter-\d+|sub-\d+-\d+)", fragment):
                    errors.append(f"{relative}: missing fragment: {link}")
    return pages, errors


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("destination", nargs="?", default="_site")
    parser.add_argument("--baseurl", default="/Notes")
    args = parser.parse_args()
    pages, errors = check_site(args.destination, args.baseurl.rstrip("/"))
    if errors:
        raise SystemExit("\n".join(errors))
    print(f"Checked {len(pages)} HTML pages: all local resources and links exist.")
